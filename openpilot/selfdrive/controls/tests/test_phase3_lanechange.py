class Store:
  def __init__(self, **values):
    self.values = {k: str(int(v)) if isinstance(v, bool) else str(v) for k, v in values.items()}

  def raw(self, k):
    return self.values.get(k)

  def tuning_level(self):
    return 3

  def honoured(self, k, level):
    return True

  def get_bool(self, k, default=False):
    return self.values.get(k, str(int(default))) in ('1', 'true', 'True', 'yes', 'on')

  def get_float(self, k, default=0.0):
    try:
      return float(self.values.get(k, default))
    except (TypeError, ValueError):
      return float(default)

  def put(self, k, v):
    self.values[k] = str(v)

  def put_bool(self, k, v):
    self.values[k] = '1' if v else '0'

  def invalidate(self, key=None):
    pass

def adopt_lane(store, **values):
  """Write prefs then adopt the Lane Changes panel (and optional Human/Turn markers)."""
  for k, v in values.items():
    if isinstance(v, bool):
      store.put_bool(k, v)
    else:
      store.put(k, v)
  store.put_bool(LANE_CHANGE_ACK, True)
  return store

def adopt_human(store, **values):
  for k, v in values.items():
    if isinstance(v, bool):
      store.put_bool(k, v)
    else:
      store.put(k, v)
  store.put_bool(HUMAN_LANE_CHANGES_ACK, True)
  return store

def adopt_turn(store, **values):
  for k, v in values.items():
    if isinstance(v, bool):
      store.put_bool(k, v)
    else:
      store.put(k, v)
  store.put_bool(TURN_DESIRES_ACK, True)
  return store


def car(**kw):
  d = {
    'vEgo': 25.0,
    'leftBlinker': True,
    'rightBlinker': False,
    'leftBlindspot': False,
    'rightBlindspot': False,
    'steeringPressed': False,
    'steeringTorque': 0.0,
    'standstill': False,
  }
  return NS(**(d | kw))


def line(y):
  return NS(x=[0.0, 20.0, 80.0], y=[y, y, y])


def model(**kw):
  d = {
    'laneLines': [line(y) for y in (-5.4, -1.8, 1.8, 5.4)],
    'roadEdges': [line(-7.0), line(7.0)],
    'position': NS(x=[0.0, 20.0, 80.0]),
    'meta': NS(laneChangeState=LCS.laneChangeStarting, laneChangeDirection=LCD.left),
  }
  return NS(**(d | kw))


class Track:
  def __init__(self, tid, d, y, speed=20.0):
    self.identifier, self.dRel, self.yRel, self.vLeadK = tid, d, y, speed
    self.vRel = 0.0

  def update(self, d, y, relative, speed):
    self.dRel, self.yRel, self.vRel, self.vLeadK = d, y, relative, speed

  def get_RadarState(self, model_prob=0.0):
    return {
      'present': True,
      'radar': True,
      'radarTrackId': self.identifier,
      'dRel': self.dRel,
      'yRel': self.yRel,
      'vRel': 0.0,
      'vLead': self.vLeadK,
      'vLeadK': self.vLeadK,
      'aLeadK': 0.0,
      'aLeadTau': 1.5,
      'modelProb': model_prob,
    }

  def potential_low_speed_lead(self, v):
    return abs(self.yRel) < 1 and v < 4 and 0.75 < self.dRel < 25


class PolicyTests(unittest.TestCase):
  def test_defaults_off_and_saved_preferences_unchanged(self):
    store = Store()
    self.assertFalse(read_settings(store).nudgeless)
    self.assertFalse(lane_change_adopted(store))
    for v in (False, True):
      # Without adoption, saved ON stays dormant and prefs are never rewritten.
      store = Store(NudgelessLaneChange=v, LaneChangeTime=2.5, MinimumLaneChangeSpeed=40)
      before = dict(store.values)
      cfg = read_settings(store)
      self.assertFalse(cfg.nudgeless)
      self.assertEqual(store.values, before)
      # After adoption, saved value is honored and still not rewritten by read.
      adopt_lane(store)
      before = dict(store.values)
      cfg = read_settings(store)
      self.assertEqual(cfg.nudgeless, v)
      self.assertEqual(cfg.delay, 2.5)
      self.assertEqual(store.values, before)

  def test_settings_units_and_stock_speed_floor(self):
    a = read_settings(adopt_lane(Store(), MinimumLaneChangeSpeed=40, LaneDetectionWidth=10))
    b = read_settings(adopt_lane(Store(IsMetric=True), MinimumLaneChangeSpeed=64.37376, LaneDetectionWidth=3.048))
    self.assertAlmostEqual(a.minimum_speed, b.minimum_speed)
    self.assertAlmostEqual(a.minimum_width, b.minimum_width)
    self.assertEqual(read_settings(adopt_lane(Store(), MinimumLaneChangeSpeed=0)).minimum_speed, STOCK_MIN_SPEED)

  def test_bad_numeric_preferences_fail_closed(self):
    for key in ('LaneChangeTime', 'LaneDetectionWidth', 'MinimumLaneChangeSpeed'):
      for value in ('nan', 'inf', '-1', 'garbage'):
        with self.subTest(key=key, value=value):
          self.assertFalse(read_settings(adopt_lane(Store(), NudgelessLaneChange=True, **{key: value})).nudgeless)

  def test_reader_fail_closed_instead_of_stale_automatic(self):
    s = adopt_lane(Store(), NudgelessLaneChange=True)
    r = LaneChangeSettingsReader(s)
    self.assertTrue(r.read(0).nudgeless)
    s.raw = lambda k: (_ for _ in ()).throw(OSError('unreadable'))
    self.assertFalse(r.read(2).nudgeless)

  def test_human_hardware_longitudinal_and_parent_gates(self):
    s = adopt_human(Store(HumanLaneChanges=True, LongitudinalTune=True))
    cp = NS(radarUnavailable=False, openpilotLongitudinalControl=True)
    self.assertTrue(read_settings(s, cp).human)
    self.assertFalse(read_settings(s).human)
    for k in ('radarUnavailable', 'openpilotLongitudinalControl'):
      bad = NS(**vars(cp))
      setattr(bad, k, k == 'radarUnavailable')
      self.assertFalse(read_settings(s, bad).human)
    self.assertFalse(read_settings(adopt_human(Store(HumanLaneChanges=True, LongitudinalTune=False)), cp).human)

  def test_delay_and_opposing_intent_blindspot_resets(self):
    for side in ('left', 'right'):
      cs = car(leftBlinker=side == 'left', rightBlinker=side == 'right')
      p = LaneChangePolicy()
      cfg = LaneChangeSettings(nudgeless=True, delay=0.2)
      self.assertFalse(p.observe(cs, True, False, cfg, model(), True))
      for _ in range(3):
        self.assertFalse(p.observe(cs, True, True, cfg, model(), True))
      self.assertTrue(p.observe(cs, True, True, cfg, model(), True))
      setattr(cs, side + 'Blindspot', True)
      self.assertFalse(p.observe(cs, True, True, cfg, model(), True))
      self.assertEqual(p.wait, 0)
      setattr(cs, side + 'Blindspot', False)
      cs.steeringPressed = True
      cs.steeringTorque = -1 if side == 'left' else 1
      self.assertFalse(p.observe(cs, True, True, cfg, model(), True))
      self.assertEqual(p.wait, 0)

  def test_safety_negative_matrix(self):
    cfg = LaneChangeSettings(nudgeless=True, delay=0)
    for kw in (
      {'rightBlinker': True},
      {'leftBlinker': False},
      {'standstill': True},
      {'vEgo': 0},
      {'vEgo': math.nan},
      {'leftBlindspot': True},
      {'steeringPressed': True, 'steeringTorque': -1},
    ):
      p = LaneChangePolicy()
      cs = car(**kw)
      p.observe(cs, True, False, cfg, model(), True)
      self.assertFalse(p.observe(cs, True, True, cfg, model(), True), kw)
    for active, valid, settings in (
      (False, True, cfg),
      (True, False, cfg),
      (True, True, replace(cfg, enabled=False)),
      (True, True, replace(cfg, nudgeless=False)),
    ):
      p = LaneChangePolicy()
      p.observe(car(), active, False, settings, model(), valid)
      self.assertFalse(p.observe(car(), active, True, settings, model(), valid))

  def test_reengage_held_signal_and_mid_signal_flip_not_automatic(self):
    p = LaneChangePolicy()
